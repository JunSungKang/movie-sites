export function t(input, ...values) {
  const key = Array.isArray(input) ? input.reduce((s, part, index) => s + (index ? '{'+(index-1)+'}' : '') + part, '') : input;
  const text = locale === 'ko' ? key : english[key] ?? key;
  return text.replace(/\{(\d+)\}/g, (match, index) => index < values.length ? String(values[index]) : match);
}
